# 1. Write a Python program to access values between index 1 and 5 in a tuple.
my_tuple = (10, 20, 30, 40, 50, 60, 70, 80)

# Slicing from index 1 to 5 (index 5 is excluded)
print("Values between index 1 and 5:", my_tuple[1:5])




# 2. Write a Python program to access alternate values between index 1 and 5 in a tuple.
my_tuple = (10, 20, 30, 40, 50, 60, 70, 80)

# Slicing from index 1 to 5 with a step of 2
print("Alternate values between index 1 and 5:", my_tuple[1:5:2])